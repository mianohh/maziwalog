# Monthly statement PDF export.

# Uses reportlab for PDF rendering.


from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def render_statement_pdf(statement) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=f"MaziwaLog Statement {statement.farmer.member_number} "
        f"{statement.year}-{statement.month:02d}",
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "Title2", parent=styles["Heading1"], fontSize=16, spaceAfter=4
    )
    small = ParagraphStyle("Small", parent=styles["Normal"], fontSize=9, textColor=colors.grey)

    story = [
        Paragraph("MaziwaLog &mdash; Monthly Milk Statement", title_style),
        Paragraph(
            f"{statement.cooler.name}, {statement.cooler.county} &nbsp;|&nbsp; "
            f"Statement period: {statement.month_name}",
            small,
        ),
        Spacer(1, 8 * mm),
    ]

    identity = [
        ["Farmer", statement.farmer.full_name],
        ["Member number", statement.farmer.member_number],
        ["Phone", statement.farmer.phone_number],
        ["Payout status", statement.get_payout_status_display()],
    ]
    if statement.coop_mpesa_payout_receipt:
        identity.append(["Co-op M-Pesa receipt", statement.coop_mpesa_payout_receipt])

    money = lambda v: f"KES {v:,.2f}"

    ledger = [
        ["Accepted litres", f"{statement.total_accepted_litres:,.2f} L"],
        ["Applied rate per litre", money(statement.applied_rate_kes)],
        ["Gross milk earnings", money(statement.gross_earnings_kes)],
        ["Store credit deduction", f"({money(statement.store_credit_deducted_kes)})"],
        ["Net payout", money(statement.net_payout_kes)],
    ]

    def styled(rows, header_row=None):
        table = Table(rows, colWidths=[75 * mm, 75 * mm])
        style = [
            ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
            ("BACKGROUND", (0, 0), (0, -1), colors.Color(0.96, 0.97, 0.95)),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 10),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ]
        if header_row:
            style += [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0d6efd")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ]
        table.setStyle(TableStyle(style))
        return table

    story.append(styled(identity))
    story.append(Spacer(1, 6 * mm))
    story.append(styled(ledger))
    story.append(Spacer(1, 8 * mm))
    story.append(
        Paragraph(
            "Non-custodial notice: MaziwaLog does not hold co-op funds. Payouts are made "
            "from the co-op's own M-Pesa Till/Paybill; the receipt code above is recorded "
            "against this statement once payment is made.",
            small,
        )
    )
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph("Generated by MaziwaLog", small))

    doc.build(story)
    return buffer.getvalue()
